CREATE TABLE avis (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id BIGINT NOT NULL UNIQUE,
  circuit_id BIGINT NOT NULL,
  guide_id BIGINT NOT NULL,
  user_subject VARCHAR(100) NOT NULL,
  auteur VARCHAR(160) NOT NULL,
  note_guide INTEGER NOT NULL CHECK(note_guide BETWEEN 1 AND 5),
  note_circuit INTEGER NOT NULL CHECK(note_circuit BETWEEN 1 AND 5),
  commentaire VARCHAR(2000) NOT NULL,
  date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  publie BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_avis_user ON avis(user_subject);
CREATE INDEX idx_avis_circuit ON avis(circuit_id);
CREATE INDEX idx_avis_guide ON avis(guide_id);
